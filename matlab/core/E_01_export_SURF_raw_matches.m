function [pts1,pts2,nK1,nK2] = ...
    rawSURFMatches(img1,img2)

    if size(img1,3) == 3
        g1 = rgb2gray( ...
            im2uint8(img1));
    else
        g1 = im2uint8(img1);
    end

    if size(img2,3) == 3
        g2 = rgb2gray( ...
            im2uint8(img2));
    else
        g2 = im2uint8(img2);
    end

    f1 = detectSURFFeatures(g1);

    f2 = detectSURFFeatures(g2);

    nK1 = f1.Count;
    nK2 = f2.Count;

    [d1,v1] = ...
        extractFeatures(g1,f1);

    [d2,v2] = ...
        extractFeatures(g2,f2);

    indexPairs = matchFeatures( ...
        d1,d2, ...
        'Unique',true, ...
        'MaxRatio',0.7);

    if isempty(indexPairs)

        pts1 = zeros(0,2);
        pts2 = zeros(0,2);

        return;

    end

    m1 = v1( ...
        indexPairs(:,1));

    m2 = v2( ...
        indexPairs(:,2));

    pts1 = m1.Location;

    pts2 = m2.Location;

end


function out = applyPWMRS( ...
    image, ...
    pwmFreqHz, ...
    exposureMs, ...
    dutyCycle, ...
    modulationDepth, ...
    readoutMs, ...
    phaseOffset, ...
    numSamples)

    img = double(image);

    H = size(img,1);

    readoutS = ...
        readoutMs / 1000;

    exposureS = ...
        exposureMs / 1000;

    rowTime = ...
        readoutS / H;

    exposureOffsets = ...
        linspace( ...
        0, ...
        exposureS, ...
        numSamples);

    rowGain = ...
        zeros(H,1);

    for rr = 1:H

        rowStart = ...
            (rr-1) * rowTime;

        sampleTimes = ...
            rowStart + ...
            exposureOffsets;

        pwmPhase = mod( ...
            sampleTimes * ...
            pwmFreqHz + ...
            phaseOffset, ...
            1);

        ledOn = ...
            pwmPhase < dutyCycle;

        intensity = ...
            (1-modulationDepth) + ...
            modulationDepth * ...
            double(ledOn);

        rowGain(rr) = ...
            mean(intensity);

    end

    out = img .* ...
        reshape(rowGain,[],1,1);

    out = uint8( ...
        min(255,max(0,round(out))));

end


function appendTable(T,fileName)

    if isfile(fileName)

        writetable( ...
            T, ...
            fileName, ...
            'WriteMode','append', ...
            'WriteVariableNames',false);

    else

        writetable( ...
            T, ...
            fileName);

    end

end