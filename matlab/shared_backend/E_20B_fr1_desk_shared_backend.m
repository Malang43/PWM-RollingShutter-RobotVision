%% ============================================================
% LOCAL FUNCTION 1
% GENERATE FINAL 100-SAMPLE ROW GAIN
%% ============================================================

function rowGain = generateRowGain( ...
    height, ...
    readoutTime, ...
    exposureTime, ...
    pwmFreq, ...
    dutyCycle, ...
    modulationDepth, ...
    phaseOffset, ...
    numSamples)


rowTime = ...
    readoutTime / height;


sampleOffsets = linspace( ...
    0, ...
    exposureTime, ...
    numSamples);


rowGain = zeros( ...
    height, ...
    1);


offIntensity = ...
    1 - modulationDepth;


for row = 1:height

    rowStart = ...
        (row-1)*rowTime;


    sampleTimes = ...
        rowStart + ...
        sampleOffsets;


    phase = mod( ...
        sampleTimes*pwmFreq + ...
        phaseOffset, ...
        1);


    ledOn = ...
        phase < dutyCycle;


    intensity = ...
        offIntensity * ...
        ones(size(sampleTimes));


    intensity(ledOn) = 1;


    rowGain(row) = ...
        mean(intensity);

end

end


%% ============================================================
% LOCAL FUNCTION 2
% APPLY ROW GAIN WITH EXPLICIT 8-BIT ROUNDING
%% ============================================================

function output = applyRowGainUint8( ...
    inputImage, ...
    rowGain)


x = double(inputImage);


for row = 1:size(x,1)

    x(row,:,:) = ...
        x(row,:,:) * ...
        rowGain(row);

end


x = round(x);

x = min( ...
    max(x,0), ...
    255);


output = uint8(x);

end


%% ============================================================
% LOCAL FUNCTION 3
% SURF RAW CORRESPONDENCES ONLY
%% ============================================================

function [p1,p2] = ...
    getSURFRawMatches( ...
    img1,img2)


p1 = zeros(0,2);
p2 = zeros(0,2);


gray1 = rgb2gray( ...
    im2uint8(img1));

gray2 = rgb2gray( ...
    im2uint8(img2));


points1 = detectSURFFeatures( ...
    gray1);

points2 = detectSURFFeatures( ...
    gray2);


if points1.Count < 8 || ...
        points2.Count < 8

    return;

end


[features1,valid1] = ...
    extractFeatures( ...
    gray1, ...
    points1);


[features2,valid2] = ...
    extractFeatures( ...
    gray2, ...
    points2);


pairs = matchFeatures( ...
    features1, ...
    features2, ...
    'Unique',true, ...
    'MaxRatio',0.7);


if size(pairs,1) < 1
    return;
end


matched1 = ...
    valid1(pairs(:,1));

matched2 = ...
    valid2(pairs(:,2));


p1 = ...
    matched1.Location;

p2 = ...
    matched2.Location;

end


%% ============================================================
% LOCAL FUNCTION 4
% SHARED MATLAB GEOMETRIC BACKEND
%% ============================================================

function R = sharedBackend( ...
    p1, ...
    p2, ...
    intrinsics, ...
    numTrials, ...
    distanceThreshold, ...
    confidence, ...
    validFractionThreshold)


%% ------------------------------------------------------------
% Initialize
%% ------------------------------------------------------------

R.FundamentalInliers = 0;

R.EssentialInliers = 0;

R.ValidFraction = 0;

R.PoseRecovered = false;

R.FailureStage = ...
    "TooFewMatches";


n = size(p1,1);


if n < 8
    return;
end


%% ------------------------------------------------------------
% Fundamental matrix
%% ------------------------------------------------------------

try

    [~,inlierF,statusF] = ...
        estimateFundamentalMatrix( ...
        p1, ...
        p2, ...
        'Method','RANSAC', ...
        'NumTrials',numTrials, ...
        'DistanceThreshold',distanceThreshold, ...
        'Confidence',confidence);

catch

    R.FailureStage = ...
        "FundamentalFailure";

    return;

end


if statusF ~= 0 || ...
        isempty(inlierF)

    R.FailureStage = ...
        "FundamentalFailure";

    return;

end


R.FundamentalInliers = ...
    sum(inlierF);


%% ------------------------------------------------------------
% Essential matrix
%% ------------------------------------------------------------

try

    [E,inlierE,statusE] = ...
        estimateEssentialMatrix( ...
        p1, ...
        p2, ...
        intrinsics, ...
        'Confidence',confidence, ...
        'MaxNumTrials',numTrials);

catch

    R.FailureStage = ...
        "EssentialFailure";

    return;

end


if statusE ~= 0 || ...
        isempty(E) || ...
        isempty(inlierE)

    R.FailureStage = ...
        "EssentialFailure";

    return;

end


nE = ...
    sum(inlierE);


R.EssentialInliers = ...
    nE;


if nE < 8

    R.FailureStage = ...
        "TooFewEssentialInliers";

    return;

end


p1E = ...
    p1(inlierE,:);

p2E = ...
    p2(inlierE,:);


%% ------------------------------------------------------------
% Pose candidate handling
%% ------------------------------------------------------------

bestValidFraction = -inf;

bestRest = [];

bestTest = [];


if ndims(E)==3

    nCandidates = ...
        size(E,3);

else

    nCandidates = 1;

end


for candidate = 1:nCandidates

    if nCandidates == 1

        Ecandidate = E;

    else

        Ecandidate = ...
            E(:,:,candidate);

    end


    try

        [Rcand,tcand,vfCand] = ...
            relativeCameraPose( ...
            Ecandidate, ...
            intrinsics, ...
            p1E, ...
            p2E);

    catch

        continue;

    end


    if ndims(Rcand)==3

        nPoseCandidates = ...
            size(Rcand,3);


        for kk = 1:nPoseCandidates

            Rtmp = ...
                Rcand(:,:,kk);


            if size(tcand,1) >= kk

                ttmp = ...
                    tcand(kk,:);

            else

                continue;

            end


            if numel(vfCand) >= kk

                vtmp = ...
                    vfCand(kk);

            else

                vtmp = ...
                    vfCand(1);

            end


            if isfinite(vtmp) && ...
                    vtmp > bestValidFraction

                bestValidFraction = ...
                    vtmp;

                bestRest = ...
                    Rtmp;

                bestTest = ...
                    ttmp;

            end

        end


    else

        if isempty(vfCand)
            continue;
        end


        vtmp = ...
            vfCand(1);


        if isfinite(vtmp) && ...
                vtmp > bestValidFraction

            bestValidFraction = ...
                vtmp;

            bestRest = ...
                Rcand;


            if size(tcand,1) > 1

                bestTest = ...
                    tcand(1,:);

            else

                bestTest = ...
                    tcand;

            end

        end

    end

end


%% ------------------------------------------------------------
% No valid pose candidate
%% ------------------------------------------------------------

if isempty(bestRest) || ...
        isempty(bestTest)

    R.FailureStage = ...
        "PoseRecoveryFailure";

    return;

end


R.ValidFraction = ...
    bestValidFraction;


%% ------------------------------------------------------------
% Shared pose criterion
%% ------------------------------------------------------------

if bestValidFraction < ...
        validFractionThreshold

    R.FailureStage = ...
        "LowValidFraction";

    return;

end


%% ------------------------------------------------------------
% Translation-vector sanity check
%% ------------------------------------------------------------

bestTest = ...
    reshape(bestTest,1,[]);


if numel(bestTest) ~= 3 || ...
        any(~isfinite(bestTest)) || ...
        norm(bestTest) < 1e-12

    R.FailureStage = ...
        "InvalidTranslation";

    return;

end


%% ------------------------------------------------------------
% Successful pose recovery
%% ------------------------------------------------------------

R.PoseRecovered = true;

R.FailureStage = ...
    "Recovered";

end