%% ============================================================
% INPUT FILES
%% ============================================================

cleanFile = repository_input(repoPaths,'main_shared_backend/experiment18J_shared_backend_clean_pairwise.csv');

pwmFile = repository_input(repoPaths,'main_shared_backend/experiment18J_shared_backend_PWM_pairwise.csv');

assert( ...
    isfile(cleanFile), ...
    'Missing file: %s', ...
    cleanFile);

assert( ...
    isfile(pwmFile), ...
    'Missing file: %s', ...
    pwmFile);

fprintf('\nExisting shared-backend results found.\n');

%% ============================================================
% LOAD DATA
%% ============================================================

cleanRows = readtable(cleanFile);
pwmRows   = readtable(pwmFile);

fprintf( ...
    'Clean pairwise rows: %d\n', ...
    height(cleanRows));

fprintf( ...
    'PWM pairwise rows: %d\n', ...
    height(pwmRows));

%% ============================================================
% FORCE IMPORTANT TEXT COLUMNS TO STRING
%% ============================================================

cleanRows.Method = ...
    string(cleanRows.Method);

pwmRows.Method = ...
    string(pwmRows.Method);

if ismember( ...
        'FailureStage', ...
        cleanRows.Properties.VariableNames)

    cleanRows.FailureStage = ...
        string(cleanRows.FailureStage);

end

if ismember( ...
        'FailureStage', ...
        pwmRows.Properties.VariableNames)

    pwmRows.FailureStage = ...
        string(pwmRows.FailureStage);

end

