function logicalVector = convertToLogical(inputVector)

    % --------------------------------------------------------
    % Already logical
    % --------------------------------------------------------

    if islogical(inputVector)

        logicalVector = ...
            inputVector;

        logicalVector = ...
            logicalVector(:);

        return;

    end

    % --------------------------------------------------------
    % Numeric 0 / 1
    % --------------------------------------------------------

    if isnumeric(inputVector)

        logicalVector = ...
            inputVector ~= 0;

        logicalVector = ...
            logicalVector(:);

        return;

    end

    % --------------------------------------------------------
    % Categorical
    % --------------------------------------------------------

    if iscategorical(inputVector)

        inputVector = ...
            string(inputVector);

    end

    % --------------------------------------------------------
    % Cell
    % --------------------------------------------------------

    if iscell(inputVector)

        inputVector = ...
            string(inputVector);

    end

    % --------------------------------------------------------
    % Character array
    % --------------------------------------------------------

    if ischar(inputVector)

        inputVector = ...
            string(inputVector);

    end

    % --------------------------------------------------------
    % String true / false / 1 / 0
    % --------------------------------------------------------

    if isstring(inputVector)

        x = lower( ...
            strtrim(inputVector));

        logicalVector = ...
            x == "true" | ...
            x == "1" | ...
            x == "yes";

        logicalVector = ...
            logicalVector(:);

        return;

    end

    error( ...
        'Unsupported PoseRecovered variable type: %s', ...
        class(inputVector));

end