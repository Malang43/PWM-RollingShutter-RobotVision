%% ============================================================

conditionSummary = table();

for m = 1:numel(methods)

    method = methods(m);

    for r = 1:numel(readouts)

        readoutMs = ...
            readouts(r);

        for p = 1:numel(phases)

            phase = ...
                phases(p);

            idx = ...
                pwmRows.Method == method & ...
                abs( ...
                    pwmRows.Phase - phase ...
                ) < 1e-9 & ...
                abs( ...
                    pwmRows.ReadoutMs - readoutMs ...
                ) < 1e-9;

            X = pwmRows(idx,:);

            assert( ...
                height(X) == 50, ...
                ['Expected 50 rows for ', ...
                 '%s phase %.3f readout %.1f ms, ', ...
                 'but found %d.'], ...
                method, ...
                phase, ...
                readoutMs, ...
                height(X));

            recovered = ...
                X.PoseRecoveredLogical;

            nRecovered = ...
                sum(recovered);

            poseFailurePercent = ...
                100 * mean(~recovered);

            medianRetention = median( ...
                X.InlierRetentionPercent, ...
                'omitnan');

            meanRetention = mean( ...
                X.InlierRetentionPercent, ...
                'omitnan');

            meanRawMatches = mean( ...
                X.RawMatches, ...
                'omitnan');

            medianRawMatches = median( ...
                X.RawMatches, ...
                'omitnan');

            meanFInliers = mean( ...
                X.FundamentalInliers, ...
                'omitnan');

            medianFInliers = median( ...
                X.FundamentalInliers, ...
                'omitnan');

            % --------------------------------------------
            % CONDITIONAL POSE DELTAS
            % ONLY recovered cases
            % --------------------------------------------

            if nRecovered > 0

                deltaRotRecovered = ...
                    X.DeltaRotationErrorDeg( ...
                        recovered);

                deltaTransRecovered = ...
                    X.DeltaTranslationRawErrorDeg( ...
                        recovered);

                medianDeltaRot = median( ...
                    deltaRotRecovered, ...
                    'omitnan');

                medianDeltaTrans = median( ...
                    deltaTransRecovered, ...
                    'omitnan');

            else

                medianDeltaRot = NaN;
                medianDeltaTrans = NaN;

            end

            row = table( ...
                method, ...
                phase, ...
                readoutMs, ...
                poseFailurePercent, ...
                nRecovered, ...
                medianRetention, ...
                meanRetention, ...
                meanRawMatches, ...
                medianRawMatches, ...
                meanFInliers, ...
                medianFInliers, ...
                medianDeltaRot, ...
                medianDeltaTrans, ...
                'VariableNames',{ ...
                'Method', ...
                'Phase', ...
                'ReadoutMs', ...
                'PoseFailurePercent', ...
                'NposeRecovered', ...
                'MedianInlierRetentionPercent', ...
                'MeanInlierRetentionPercent', ...
                'MeanRawMatches', ...
                'MedianRawMatches', ...
                'MeanFundamentalInliers', ...
                'MedianFundamentalInliers', ...
                'MedianDeltaRotationErrorDeg', ...
                'MedianDeltaTranslationRawErrorDeg'});

