    'Method', ...
    'PairID', ...
    'Phase', ...
    'ReadoutMs', ...
    'RawMatches', ...
    'FundamentalInliers', ...
    'PoseRecoveredLogical', ...
    'FailureStage', ...
    'RotationErrorDeg', ...
    'TranslationRawErrorDeg', ...
    'TranslationSignInvariantErrorDeg', ...
    'InlierRetentionPercent', ...
    'DeltaRotationErrorDeg', ...
    'DeltaTranslationRawErrorDeg'};

