    cleanSummary, ...
    cleanSummaryFile);

%% ============================================================
% CONDITION SETTINGS
%% ============================================================

phases = [ ...
    0, ...
    0.125, ...
    0.25, ...
    0.5, ...
    0.875];

readouts = [ ...
    5, ...
    10, ...
    15, ...
    20, ...
    25, ...
    30];

%% ============================================================
