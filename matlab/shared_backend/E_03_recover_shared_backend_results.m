close all;

%% ============================================================
% EXPERIMENT 18J - FINAL RECOVERY SCRIPT
%
% PURPOSE:
% Recover all final summaries from the ALREADY COMPLETED
% shared-backend pairwise results.
%
% NO SURF EXTRACTION
% NO LIGHTGLUE EXTRACTION
% NO RANSAC RERUN
%
% Save as:
% E_03_recover_shared_backend_results.m
%% ============================================================

baseRoot = repoPaths.resultsRoot;

