    method = methods(m);

    nClean = sum( ...
        cleanRows.Method == method);

    nPWM = sum( ...
        pwmRows.Method == method);

    fprintf( ...
        '%s clean rows = %d\n', ...
        method, ...
        nClean);

    fprintf( ...
        '%s PWM rows   = %d\n', ...
        method, ...
        nPWM);

    assert( ...
        nClean == 50, ...
        '%s clean rows should be 50.', ...
        method);

    assert( ...
        nPWM == 1500, ...
        '%s PWM rows should be 1500.', ...
        method);

end

fprintf('\nIntegrity check passed.\n');

%% ============================================================
% CLEAN SUMMARY
%% ============================================================

cleanSummary = table();

for m = 1:numel(methods)

    method = methods(m);

    X = cleanRows( ...
        cleanRows.Method == method, :);

    recovered = ...
        X.PoseRecoveredLogical;

    nRecovered = ...
        sum(recovered);

    if nRecovered > 0

        medRot = median( ...
            X.RotationErrorDeg(recovered), ...
            'omitnan');

        medTransRaw = median( ...
            X.TranslationRawErrorDeg(recovered), ...
            'omitnan');

        medTransSI = median( ...
            X.TranslationSignInvariantErrorDeg(recovered), ...
            'omitnan');

    else

        medRot = NaN;
        medTransRaw = NaN;
        medTransSI = NaN;

    end

    row = table( ...
        method, ...
        100 * mean(recovered), ...
        nRecovered, ...
        medRot, ...
        medTransRaw, ...
        medTransSI, ...
        median( ...
            X.FundamentalInliers, ...
            'omitnan'), ...
        median( ...
            X.RawMatches, ...
            'omitnan'), ...
        'VariableNames',{ ...
        'Method', ...
        'CleanRecoveryPercent', ...
        'NRecovered', ...
        'MedianRotationErrorDeg', ...
        'MedianTranslationRawErrorDeg', ...
        'MedianTranslationSignInvariantErrorDeg', ...
        'MedianFundamentalInliers', ...
        'MedianRawMatches'});

    cleanSummary = [ ...
        cleanSummary; ...
        row];

