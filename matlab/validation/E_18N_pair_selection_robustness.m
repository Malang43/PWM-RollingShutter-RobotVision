%% ============================================================
% LOCAL FUNCTION 1
% FINAL PWM ROW-GAIN MODEL
%% ============================================================

function rowGain = generateRowGain( ...
    H, ...
    readoutTime, ...
    exposureTime, ...
    pwmFreq, ...
    dutyCycle, ...
    modulationDepth, ...
    phaseOffset, ...
    numSamples)


rowTime = ...
    readoutTime / H;


sampleOffsets = linspace( ...
    0, ...
    exposureTime, ...
    numSamples);


rowGain = zeros( ...
    H, ...
    1);


offIntensity = ...
    1 - modulationDepth;


for row = 1:H

    rowStart = ...
        (row-1) * ...
        rowTime;


    sampleTimes = ...
        rowStart + ...
        sampleOffsets;


    phase = mod( ...
        sampleTimes*pwmFreq + ...
        phaseOffset, ...
        1);


    ledOn = ...
        phase < dutyCycle;


    intensity = ...
        offIntensity * ...
        ones(size(sampleTimes));


    intensity(ledOn) = 1;


    rowGain(row) = ...
        mean(intensity);

end

end


%% ============================================================
% LOCAL FUNCTION 2
% APPLY ROW GAIN
%% ============================================================

function output = applyRowGainUint8( ...
    inputImage, ...
    rowGain)


x = double( ...
    inputImage);


for row = 1:size(x,1)

    x(row,:,:) = ...
        x(row,:,:) * ...
        rowGain(row);

end


x = round(x);

x = min( ...
    max(x,0), ...
    255);


output = ...
    uint8(x);

end


%% ============================================================
% LOCAL FUNCTION 3
% SURF RAW CORRESPONDENCES
%% ============================================================

function [p1,p2] = ...
    getSURFRawMatches( ...
    img1,img2)


p1 = zeros(0,2);

p2 = zeros(0,2);


gray1 = rgb2gray( ...
    im2uint8(img1));


gray2 = rgb2gray( ...
    im2uint8(img2));


points1 = ...
    detectSURFFeatures( ...
    gray1);


points2 = ...
    detectSURFFeatures( ...
    gray2);


if points1.Count < 8 || ...
        points2.Count < 8

    return;

end


[features1,valid1] = ...
    extractFeatures( ...
    gray1, ...
    points1);


[features2,valid2] = ...
    extractFeatures( ...
    gray2, ...
    points2);


pairs = matchFeatures( ...
    features1, ...
    features2, ...
    'Unique',true, ...
    'MaxRatio',0.7);


if isempty(pairs)

    return;

end


matched1 = ...
    valid1(pairs(:,1));


matched2 = ...
    valid2(pairs(:,2));


p1 = ...
    matched1.Location;


p2 = ...
    matched2.Location;

end


%% ============================================================
% LOCAL FUNCTION 4
% SHARED GEOMETRIC BACKEND
%% ============================================================

function R = sharedBackend( ...
    p1, ...
    p2, ...
    intrinsics, ...
    numTrials, ...
    distanceThreshold, ...
    confidence, ...
    validFractionThreshold)


R.FundamentalInliers = 0;

R.EssentialInliers = 0;

R.ValidFraction = NaN;

R.PoseRecovered = false;

R.FailureStage = ...
    "TooFewMatches";


if size(p1,1) < 8

    return;

end


%% Fundamental matrix

try

    [~,inlierF,statusF] = ...
        estimateFundamentalMatrix( ...
        p1, ...
        p2, ...
        'Method','RANSAC', ...
        'NumTrials',numTrials, ...
        'DistanceThreshold',distanceThreshold, ...
        'Confidence',confidence);

catch

    R.FailureStage = ...
        "FundamentalFailure";

    return;

end


if statusF ~= 0 || ...
        isempty(inlierF)

    R.FailureStage = ...
        "FundamentalFailure";

    return;

end


R.FundamentalInliers = ...
    sum(inlierF);


%% Essential matrix

try

    [E,inlierE,statusE] = ...
        estimateEssentialMatrix( ...
        p1, ...
        p2, ...
        intrinsics, ...
        'Confidence',confidence, ...
        'MaxNumTrials',numTrials);

catch

    R.FailureStage = ...
        "EssentialFailure";

    return;

end


if statusE ~= 0 || ...
        isempty(E) || ...
        isempty(inlierE)

    R.FailureStage = ...
        "EssentialFailure";

    return;

end


R.EssentialInliers = ...
    sum(inlierE);


if R.EssentialInliers < 8

    R.FailureStage = ...
        "TooFewEssentialInliers";

    return;

end


p1E = ...
    p1(inlierE,:);


p2E = ...
    p2(inlierE,:);


%% Pose candidate handling

bestVF = -inf;

bestR = [];

bestT = [];


if ndims(E)==3

    nCandidates = ...
        size(E,3);

else

    nCandidates = 1;

end


for candidate = 1:nCandidates

    if nCandidates == 1

        Ecandidate = E;

    else

        Ecandidate = ...
            E(:,:,candidate);

    end


    try

        [Rcand,tcand,vfCand] = ...
            relativeCameraPose( ...
            Ecandidate, ...
            intrinsics, ...
            p1E, ...
            p2E);

    catch

        continue;

    end


    if isempty(vfCand)
        continue;
    end


    if ndims(Rcand)==3

        nPoseCandidates = ...
            size(Rcand,3);

    else

        nPoseCandidates = 1;

    end


    for kk = 1:nPoseCandidates

        if nPoseCandidates == 1

            Rtmp = ...
                squeeze(Rcand);

        else

            Rtmp = ...
                Rcand(:,:,kk);

        end


        if size(tcand,1) >= kk

            ttmp = ...
                tcand(kk,:);

        elseif size(tcand,1)==3 && ...
                size(tcand,2)>=kk

            ttmp = ...
                tcand(:,kk)';

        else

            ttmp = ...
                tcand(1,:);

        end


        if numel(vfCand) >= kk

            vtmp = ...
                vfCand(kk);

        else

            vtmp = ...
                vfCand(1);

        end


        if isfinite(vtmp) && ...
                vtmp > bestVF

            bestVF = ...
                vtmp;

            bestR = ...
                Rtmp;

            bestT = ...
                ttmp;

        end

    end

end


if isempty(bestR) || ...
        isempty(bestT)

    R.FailureStage = ...
        "PoseRecoveryFailure";

    return;

end


R.ValidFraction = ...
    bestVF;


if bestVF < ...
        validFractionThreshold

    R.FailureStage = ...
        "LowValidFraction";

    return;

end


bestT = ...
    bestT(:);


if numel(bestT) ~= 3 || ...
        any(~isfinite(bestT)) || ...
        norm(bestT) < 1e-12

    R.FailureStage = ...
        "InvalidTranslation";

    return;

end


R.PoseRecovered = ...
    true;


R.FailureStage = ...
    "Recovered";

end