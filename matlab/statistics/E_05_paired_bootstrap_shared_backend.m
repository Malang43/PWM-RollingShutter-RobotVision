clc;
clear;

% Repository copy: path handling only; original provenance in MANIFEST.md.
addpath(fileparts(fileparts(mfilename('fullpath'))));
repoPaths = repository_paths('');

close all;

%% ============================================================
% EXPERIMENT 18K
% PAIRED / CLUSTER BOOTSTRAP FOR SHARED-BACKEND COMPARISON
%
% Dataset:
% Existing experiment18J shared-backend PWM pairwise results.
%
% Purpose:
% Account for repeated use of the same 50 image pairs across
% the 30 phase-readout conditions.
%
% Bootstrap unit:
% PairID
%
% Each resampled PairID carries all 30 conditions for both:
%   SURF
%   SuperPoint+LightGlue
%
% No feature extraction.
% No RANSAC rerun.
% No new dataset.
%% ============================================================

rootDir = repository_output(repoPaths,'main_shared_backend');

inputFile = repository_input(repoPaths,'main_shared_backend/experiment18J_shared_backend_PWM_pairwise.csv');

assert( ...
    isfile(inputFile), ...
    'Missing input file:\n%s', ...
    inputFile);

%% ============================================================
% SETTINGS
%% ============================================================

N_BOOT = 5000;

BOOT_SEED = 1805001;

rng(BOOT_SEED,'twister');

methods = [ ...
    "SURF"; ...
    "LightGlue"];

%% ============================================================
% LOAD DATA
%% ============================================================

T = readtable(inputFile);

T.Method = string(T.Method);

%% ------------------------------------------------------------
% PoseRecovered -> logical
%% ------------------------------------------------------------

if islogical(T.PoseRecovered)

    T.PoseRecoveredLogical = ...
        T.PoseRecovered;

elseif isnumeric(T.PoseRecovered)

    T.PoseRecoveredLogical = ...
        T.PoseRecovered ~= 0;

else

    x = lower( ...
        strtrim( ...
            string(T.PoseRecovered)));

    T.PoseRecoveredLogical = ...
        x == "true" | ...
        x == "1" | ...
        x == "yes";

end

%% ============================================================
% CHECK REQUIRED VARIABLES
%% ============================================================

requiredVariables = { ...
    'Method', ...
    'PairID', ...
    'Phase', ...
    'ReadoutMs', ...
    'PoseRecoveredLogical', ...
    'InlierRetentionPercent'};

for k = 1:numel(requiredVariables)

    assert( ...
        ismember( ...
            requiredVariables{k}, ...
            T.Properties.VariableNames), ...
        'Missing variable: %s', ...
        requiredVariables{k});

end

%% ============================================================
% BASIC INTEGRITY
%% ============================================================

pairIDs = unique(T.PairID);

pairIDs = sort(pairIDs);

nPairs = numel(pairIDs);

fprintf('\n============================================\n');
fprintf('EXPERIMENT 18K - CLUSTER BOOTSTRAP\n');
fprintf('============================================\n\n');

fprintf('PWM rows loaded: %d\n',height(T));
fprintf('Unique PairIDs: %d\n',nPairs);

assert( ...
    nPairs == 50, ...
    'Expected 50 unique PairIDs.');

for m = 1:numel(methods)

    method = methods(m);

    X = T(T.Method == method,:);

    fprintf( ...
        '%s rows: %d\n', ...
        method, ...
        height(X));

    assert( ...
        height(X) == 1500, ...
        '%s should contain 1500 rows.', ...
        method);

end

%% ============================================================
% CHECK MATCHED CONDITION STRUCTURE
%% ============================================================

conditions = unique( ...
    T(:,{'Phase','ReadoutMs'}), ...
    'rows');

conditions = sortrows( ...
    conditions, ...
    {'ReadoutMs','Phase'});

nConditions = height(conditions);

fprintf( ...
    'Unique phase-readout conditions: %d\n', ...
    nConditions);

assert( ...
    nConditions == 30, ...
    'Expected 30 conditions.');

%% ============================================================
% OBSERVED STATISTICS
%% ============================================================

obs = calculateStatistics( ...
    T, ...
    conditions);

fprintf('\nOBSERVED RESULTS\n');

fprintf( ...
    'SURF failure = %.3f%%\n', ...
    obs.SURF_Failure);

fprintf( ...
    'LightGlue failure = %.3f%%\n', ...
    obs.LightGlue_Failure);

fprintf( ...
    'Failure difference = %.3f percentage points\n', ...
    obs.FailureDifference);

fprintf( ...
    'SURF mean condition median retention = %.3f%%\n', ...
    obs.SURF_Retention);

fprintf( ...
    'LightGlue mean condition median retention = %.3f%%\n', ...
    obs.LightGlue_Retention);

fprintf( ...
    'Retention difference = %.3f percentage points\n', ...
    obs.RetentionDifference);

%% ============================================================
% BOOTSTRAP ARRAYS
%% ============================================================

bootSURFFailure = ...
    nan(N_BOOT,1);

bootLGFailure = ...
    nan(N_BOOT,1);

bootFailureDifference = ...
    nan(N_BOOT,1);

bootSURFRetention = ...
    nan(N_BOOT,1);

bootLGRetention = ...
    nan(N_BOOT,1);

bootRetentionDifference = ...
    nan(N_BOOT,1);

%% ============================================================
% CLUSTER BOOTSTRAP
%% ============================================================

fprintf('\nRunning %d pair-level bootstrap replicates...\n',N_BOOT);

for b = 1:N_BOOT

    % --------------------------------------------------------
    % Resample the 50 PairIDs with replacement
    % --------------------------------------------------------

    sampledPositions = ...
        randi( ...
            nPairs, ...
            nPairs, ...
            1);

    sampledPairIDs = ...
        pairIDs(sampledPositions);

    % --------------------------------------------------------
    % Construct bootstrap table.
    %
    % IMPORTANT:
    % A PairID sampled multiple times must appear multiple
    % times in the bootstrap sample.
    % --------------------------------------------------------

    TB = T([],:);

    for j = 1:nPairs

        pid = ...
            sampledPairIDs(j);

        rows = ...
            T(T.PairID == pid,:);

        TB = [TB; rows];

    end

    % --------------------------------------------------------
    % Calculate same manuscript-level statistics
    % --------------------------------------------------------

    S = calculateStatistics( ...
        TB, ...
        conditions);

    bootSURFFailure(b) = ...
        S.SURF_Failure;

    bootLGFailure(b) = ...
        S.LightGlue_Failure;

    bootFailureDifference(b) = ...
        S.FailureDifference;

    bootSURFRetention(b) = ...
        S.SURF_Retention;

    bootLGRetention(b) = ...
        S.LightGlue_Retention;

    bootRetentionDifference(b) = ...
        S.RetentionDifference;

    if mod(b,500) == 0

        fprintf( ...
            'Bootstrap %d / %d\n', ...
            b, ...
            N_BOOT);

    end

end

%% ============================================================
% 95% PERCENTILE CONFIDENCE INTERVALS
%% ============================================================

alpha = 0.05;

failureDiffCI = ...
    prctile( ...
        bootFailureDifference, ...
        [100*alpha/2, ...
         100*(1-alpha/2)]);

retentionDiffCI = ...
    prctile( ...
        bootRetentionDifference, ...
        [100*alpha/2, ...
         100*(1-alpha/2)]);

surfFailureCI = ...
    prctile( ...
        bootSURFFailure, ...
        [2.5 97.5]);

lgFailureCI = ...
    prctile( ...
        bootLGFailure, ...
        [2.5 97.5]);

surfRetentionCI = ...
    prctile( ...
        bootSURFRetention, ...
        [2.5 97.5]);

lgRetentionCI = ...
    prctile( ...
        bootLGRetention, ...
        [2.5 97.5]);

%% ============================================================
% SUMMARY TABLE
%% ============================================================

Metric = [ ...
    "SURF pose failure (%)"; ...
    "LightGlue pose failure (%)"; ...
    "Failure difference, SURF-LightGlue (pp)"; ...
    "SURF mean condition median retention (%)"; ...
    "LightGlue mean condition median retention (%)"; ...
    "Retention difference, LightGlue-SURF (pp)"];

Observed = [ ...
    obs.SURF_Failure; ...
    obs.LightGlue_Failure; ...
    obs.FailureDifference; ...
    obs.SURF_Retention; ...
    obs.LightGlue_Retention; ...
    obs.RetentionDifference];

CI95_Lower = [ ...
    surfFailureCI(1); ...
    lgFailureCI(1); ...
    failureDiffCI(1); ...
    surfRetentionCI(1); ...
    lgRetentionCI(1); ...
    retentionDiffCI(1)];

CI95_Upper = [ ...
    surfFailureCI(2); ...
    lgFailureCI(2); ...
    failureDiffCI(2); ...
    surfRetentionCI(2); ...
    lgRetentionCI(2); ...
    retentionDiffCI(2)];

summaryTable = table( ...
    Metric, ...
    Observed, ...
    CI95_Lower, ...
    CI95_Upper);

%% ============================================================
% SAVE BOOTSTRAP DISTRIBUTIONS
%% ============================================================

bootstrapTable = table( ...
    (1:N_BOOT)', ...
    bootSURFFailure, ...
    bootLGFailure, ...
    bootFailureDifference, ...
    bootSURFRetention, ...
    bootLGRetention, ...
    bootRetentionDifference, ...
    'VariableNames',{ ...
    'BootstrapID', ...
    'SURF_FailurePercent', ...
    'LightGlue_FailurePercent', ...
    'FailureDifference_pp', ...
    'SURF_MeanConditionMedianRetentionPercent', ...
    'LightGlue_MeanConditionMedianRetentionPercent', ...
    'RetentionDifference_pp'});

%% ============================================================
% SAVE FILES
%% ============================================================

summaryFile = fullfile( ...
    rootDir, ...
    'experiment18K_cluster_bootstrap_summary.csv');

bootstrapFile = fullfile( ...
    rootDir, ...
    'experiment18K_cluster_bootstrap_distributions.csv');

writetable( ...
    summaryTable, ...
    summaryFile);

writetable( ...
    bootstrapTable, ...
    bootstrapFile);

%% ============================================================
% FINAL OUTPUT
%% ============================================================

fprintf('\n\n');
fprintf('============================================\n');
fprintf('EXPERIMENT 18K COMPLETE\n');
fprintf('============================================\n\n');

disp(summaryTable);

fprintf('\nKEY PAIRED / CLUSTER BOOTSTRAP RESULTS\n\n');

fprintf( ...
    ['Failure difference = %.3f pp ', ...
     '[95%% cluster-bootstrap CI %.3f, %.3f]\n'], ...
    obs.FailureDifference, ...
    failureDiffCI(1), ...
    failureDiffCI(2));

fprintf( ...
    ['Retention difference = %.3f pp ', ...
     '[95%% cluster-bootstrap CI %.3f, %.3f]\n'], ...
    obs.RetentionDifference, ...
    retentionDiffCI(1), ...
    retentionDiffCI(2));

fprintf('\nSaved:\n');
fprintf('%s\n',summaryFile);
fprintf('%s\n',bootstrapFile);

fprintf('\nDONE.\n');

%% ============================================================
% LOCAL FUNCTION
%% ============================================================

function S = calculateStatistics(T,conditions)

    % --------------------------------------------------------
    % METHOD TABLES
    % --------------------------------------------------------

    surf = ...
        T(T.Method == "SURF",:);

    lg = ...
        T(T.Method == "LightGlue",:);

    % --------------------------------------------------------
    % FAILURE
    % --------------------------------------------------------

    S.SURF_Failure = ...
        100 * mean( ...
            ~surf.PoseRecoveredLogical);

    S.LightGlue_Failure = ...
        100 * mean( ...
            ~lg.PoseRecoveredLogical);

    S.FailureDifference = ...
        S.SURF_Failure - ...
        S.LightGlue_Failure;

    % --------------------------------------------------------
    % CONDITION-LEVEL MEDIAN RETENTION
    % --------------------------------------------------------

    surfConditionMedian = ...
        nan(height(conditions),1);

    lgConditionMedian = ...
        nan(height(conditions),1);

    for c = 1:height(conditions)

        phase = ...
            conditions.Phase(c);

        readout = ...
            conditions.ReadoutMs(c);

        idxSurf = ...
            abs(surf.Phase-phase) < 1e-9 & ...
            abs(surf.ReadoutMs-readout) < 1e-9;

        idxLG = ...
            abs(lg.Phase-phase) < 1e-9 & ...
            abs(lg.ReadoutMs-readout) < 1e-9;

        surfConditionMedian(c) = ...
            median( ...
                surf.InlierRetentionPercent(idxSurf), ...
                'omitnan');

        lgConditionMedian(c) = ...
            median( ...
                lg.InlierRetentionPercent(idxLG), ...
                'omitnan');

    end

    S.SURF_Retention = ...
        mean( ...
            surfConditionMedian, ...
            'omitnan');

    S.LightGlue_Retention = ...
        mean( ...
            lgConditionMedian, ...
            'omitnan');

    S.RetentionDifference = ...
        S.LightGlue_Retention - ...
        S.SURF_Retention;

end